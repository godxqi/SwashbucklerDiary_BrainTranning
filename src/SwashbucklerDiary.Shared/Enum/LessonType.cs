namespace SwashbucklerDiary.Shared
{
    /// <summary>
    /// 课题类型（方法文档之外的自定义维度）。它回答的是「这次功课属于哪一类」，
    /// 不是诊断，也不要求一次只选一个——一次课题同时踩中「边界 + 被评价」是常态。
    /// <para>
    /// 从 1 开始、0 视为未选择，与 <see cref="MoodKind"/> 同一个约定。
    /// 落点是课题正文 4.8 的类型文字；类型本身不单独建表，所以加一个值只需要改这里、
    /// <c>lesson-type-icons.json</c> 和 i18n 的 key（key 就是枚举名）。
    /// </para>
    /// </summary>
    public enum LessonType
    {
        /// <summary>
        /// 边界：我能不能说「不」，能不能守住自己的时间、情绪和资源。
        /// 典型场景：总被临时加活、被追问隐私、不好意思拒绝。
        /// </summary>
        /// <remarks>
        /// 思想来源：阿德勒的「课题分离」（岸见一郎《被讨厌的勇气》把这个说法通俗化）；
        /// Henry Cloud 与 John Townsend, <i>Boundaries</i> (1992)；
        /// 家庭系统理论里的自我分化（Bowen）。这些是解释框架，不是诊断标准。
        /// </remarks>
        Boundary = 1,

        /// <summary>
        /// 被评价：对方怎么看我，我有多怕被否定。
        /// 典型场景：被说「你不行」时的羞耻或愤怒、被比较。
        /// </summary>
        /// <remarks>
        /// 思想来源：阿德勒「一切烦恼都是人际关系的烦恼」（经岸见一郎《被讨厌的勇气》转述）；
        /// 库利「镜中我」（looking-glass self, 1902）；萨特「他人即地狱」（《禁闭》, 1944）。
        /// </remarks>
        BeingJudged = 2,

        /// <summary>
        /// 信任：能不能依靠对方、承诺是否兑现。
        /// 典型场景：答应的事没做到、被隐瞒、被背叛。
        /// </summary>
        /// <remarks>
        /// 思想来源：鲍尔比与安斯沃斯的依恋理论；
        /// 埃里克森「信任 vs. 不信任」（《童年与社会》, 1950）。
        /// </remarks>
        Trust = 3,

        /// <summary>
        /// 表达：我能不能说出真实需求，对方能不能听懂。
        /// 典型场景：想说不敢说、说了被误解、绕着说。
        /// </summary>
        /// <remarks>
        /// 思想来源：马歇尔·卢森堡「非暴力沟通」（观察、感受、需要、请求, 1999）；
        /// 卡尔·罗杰斯「无条件积极关注」与积极倾听。
        /// </remarks>
        Expression = 4,

        /// <summary>
        /// 冲突：意见不合时怎么处理——回避、对抗、妥协还是合作。
        /// 典型场景：吵架后冷战、一方总让步。
        /// </summary>
        /// <remarks>
        /// 思想来源：Thomas-Kilmann 冲突模式（竞争、合作、妥协、回避、迁就, 1974）；
        /// 费希尔与尤里《谈判力》（立场 vs. 利益, 1981）。
        /// </remarks>
        Conflict = 5,

        /// <summary>
        /// 依赖：过度依赖或过度独立，谁在照顾谁。
        /// 典型场景：对方不回消息就慌、什么都不敢麻烦别人。
        /// </summary>
        /// <remarks>
        /// 思想来源：依恋理论（焦虑型/回避型依恋、分离焦虑）；
        /// 卡伦·霍妮「趋向他人」（《我们内心的冲突》, 1945）；
        /// 共依存（codependency）的通俗文献（Melody Beattie, 1986）。
        /// </remarks>
        Dependence = 6,

        /// <summary>
        /// 亲密：靠近与被看见，脆弱、暴露、亲密距离。
        /// 典型场景：想靠近又怕受伤、一亲近就想逃。
        /// </summary>
        /// <remarks>
        /// 思想来源：埃里克森「亲密 vs. 孤独」（1950）；依恋理论；
        /// 苏·约翰逊「情绪取向治疗」（EFT）；布琳·布朗《脆弱的力量》（2012）——
        /// 脆弱不是软弱，而是连接的起点。
        /// </remarks>
        Intimacy = 7,

        /// <summary>
        /// 权威：和父母、领导、长辈等权力关系的模式。
        /// 典型场景：面对领导不敢提异议、习惯性讨好长辈。
        /// </summary>
        /// <remarks>
        /// 思想来源：阿德勒的自卑/优越情结；埃里克·伯恩「沟通分析」
        /// （父母/成人/儿童自我状态, 1961）；米尔格拉姆服从实验（1963）；
        /// 爱丽丝·米勒《天才儿童的悲剧》（1979）。
        /// </remarks>
        Authority = 8,
    }
}
